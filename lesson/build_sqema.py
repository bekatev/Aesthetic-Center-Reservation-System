def rfonts(run, name):
    rPr = run._element.get_or_add_rPr()
    el = rPr.find(qn("w:rFonts"))
    if el is None:
        el = OxmlElement("w:rFonts")
        rPr.append(el)
    for attr in ("w:ascii", "w:hAnsi", "w:cs", "w:eastAsia"):
        el.set(qn(attr), name)


def set_para(p, text, size=14, bold=False):
    for r in list(p.runs):
        r._element.getparent().remove(r._element)
    run = p.add_run(text)
    run.bold = bold
    run.font.size = Pt(size)
    run.font.name = FONT
    run.font.color.rgb = INK
    rfonts(run, FONT)


def append_run(p, text, size=14, bold=False):
    run = p.add_run(text)
    run.bold = bold
    run.font.size = Pt(size)
    run.font.name = FONT
    run.font.color.rgb = INK
    rfonts(run, FONT)


def insert_after(paragraph, text, size=14):
    from docx.text.paragraph import Paragraph

    new_p = OxmlElement("w:p")
    paragraph._p.addnext(new_p)
    p = Paragraph(new_p, paragraph._parent)
    set_para(p, text, size=size)
    return p


def fill_blank_after(cell, prompt_start, text):
    paras = list(cell.paragraphs)
    for i, p in enumerate(paras):
        if p.text.strip().startswith(prompt_start):
            for q in paras[i + 1 :]:
                raw = q.text.strip()
                if raw == "" or set(raw) <= {"."}:
                    set_para(q, text)
                    return
            insert_after(p, text)
            return
    raise SystemExit("prompt missing: " + prompt_start)


def replace_dotted(cell, texts):
    slots = [p for p in cell.paragraphs if p.text.strip().startswith(".....")]
    if len(slots) < len(texts):
        raise SystemExit(f"need {len(texts)} dotted lines, have {len(slots)}")
    for p, text in zip(slots, texts):
        set_para(p, text)


