def body(doc, text, size=12, after=6):
    p = doc.add_paragraph()
    set_space(p, 0, after, 1.12)
    add_text(p, text, size=size)
    return p


def field(doc, label, text):
    table = doc.add_table(rows=1, cols=1)
    set_table_width(table)
    cell = table.cell(0, 0)
    cell.text = ""
    shade(cell, "FBF6EE")
    borders(cell, "E7DCCB")
    margins(cell, 70, 80, 110, 110)
    p = cell.paragraphs[0]
    set_space(p, 0, 2)
    add_text(p, label, size=11, bold=True, color=MAROON)
    p2 = cell.add_paragraph()
    set_space(p2, 0, 0, 1.1)
    add_text(p2, text, size=11)
    gap = doc.add_paragraph()
    set_space(gap, 0, 4)


def two(doc, left_label, left, right_label, right):
    table = doc.add_table(rows=1, cols=2)
    set_table_width(table)
    for cell, label, text in (
        (table.cell(0, 0), left_label, left),
        (table.cell(0, 1), right_label, right),
    ):
        cell.text = ""
        shade(cell, "FBF6EE")
        borders(cell, "E7DCCB")
        margins(cell, 70, 80, 100, 100)
        p = cell.paragraphs[0]
        set_space(p, 0, 2)
        add_text(p, label, size=11, bold=True, color=MAROON)
        for part in text.split("\n"):
            bp = cell.add_paragraph()
            set_space(bp, 0, 2, 1.08)
            add_text(bp, part, size=11)
    gap = doc.add_paragraph()
    set_space(gap, 0, 4)


